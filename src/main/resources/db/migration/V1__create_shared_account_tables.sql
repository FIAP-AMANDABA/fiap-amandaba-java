-- Usar apenas em schema Oracle novo, sem as tabelas criadas pelo script da disciplina de BD.
-- Em schema compartilhado existente, executar a aplicacao com FLYWAY_ENABLED=false.
CREATE TABLE TAB_USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NM_USUARIO VARCHAR2(150) NOT NULL,
    NR_CPF_USUARIO VARCHAR2(11) NOT NULL UNIQUE,
    DT_NASCIMENTO_USUARIO DATE,
    DS_EMAIL_USUARIO VARCHAR2(150) NOT NULL UNIQUE,
    NR_TELEFONE_USUARIO VARCHAR2(20),
    DS_SENHA_HASH_USUARIO VARCHAR2(255) NOT NULL,
    DT_CADASTRO_USUARIO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ST_USUARIO VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT CK_TAB_USUARIO_STATUS CHECK (ST_USUARIO IN ('ATIVO','INATIVO'))
);

CREATE TABLE TAB_TUTOR (
    ID_TUTOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO_TUTOR NUMBER NOT NULL UNIQUE,
    CONSTRAINT FK_TAB_TUTOR_USUARIO FOREIGN KEY (ID_USUARIO_TUTOR) REFERENCES TAB_USUARIO(ID_USUARIO)
);

CREATE TABLE TAB_VETERINARIO (
    ID_VETERINARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO_VETERINARIO NUMBER NOT NULL UNIQUE,
    NR_CRMV_VETERINARIO VARCHAR2(20) NOT NULL UNIQUE,
    ST_VETERINARIO VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT FK_TAB_VETERINARIO_USUARIO FOREIGN KEY (ID_USUARIO_VETERINARIO) REFERENCES TAB_USUARIO(ID_USUARIO),
    CONSTRAINT CK_TAB_VETERINARIO_STATUS CHECK (ST_VETERINARIO IN ('ATIVO','INATIVO'))
);
