DROP TABLE aman_users;

CREATE TABLE TAB_USUARIO (
     ID_USUARIO              NUMBER GENERATED BY DEFAULT AS IDENTITY,

     NM_USUARIO              VARCHAR2(150) NOT NULL,
     NR_CPF_USUARIO          VARCHAR2(11) NOT NULL,
     DT_NASCIMENTO_USUARIO   DATE,
     DS_EMAIL_USUARIO        VARCHAR2(150) NOT NULL,
     NR_TELEFONE_USUARIO     VARCHAR2(20),
     DS_SENHA_HASH_USUARIO   VARCHAR2(255) NOT NULL,

     DT_CADASTRO_USUARIO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
     ST_USUARIO              VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,

     CONSTRAINT PK_TAB_USUARIO
         PRIMARY KEY (ID_USUARIO),

     CONSTRAINT UK_CPF_USUARIO
         UNIQUE (NR_CPF_USUARIO),

     CONSTRAINT UK_EMAIL_USUARIO
         UNIQUE (DS_EMAIL_USUARIO),

     CONSTRAINT CK_STATUS_USUARIO
         CHECK (
             ST_USUARIO IN ('ATIVO', 'INATIVO')
             )
);